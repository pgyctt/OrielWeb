namespace OrielWeb.Platform.Windows.WebView2.Utilities;

// 下面三组枚举的每一个值都取自上游 WebView2.dll 的元数据（FieldDef 的 Constant blob），
// 不是照着文档或记忆敲的。它们与 Windows 的 WM_MOUSE* 只是部分重合：
//   WHEEL=0x020A 与 WM_MOUSEWHEEL 一致，但 HORIZONTAL_WHEEL=0x020E 与 WM_MOUSEHWHEEL(0x020E) 一致，
//   而 LEAVE=0x02A3 才是 WM_MOUSELEAVE——曾经把 WHEEL 写成 0x020E、LEAVE 写成 0x020A，
//   症状是"滚轮完全不滚"外加"鼠标移出后 hover 不清"，且两者都不报错。
// 改动前先跑 tests/OrielWeb.Tests 里的 WebView2EnumTests，它逐值钉住了与上游的对应关系。

