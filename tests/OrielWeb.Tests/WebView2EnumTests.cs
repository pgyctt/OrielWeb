using OrielWeb.Platform.Windows.WebView2.Utilities;
using Xunit;

namespace OrielWeb.Tests;

/// <summary>
/// WebView2 枚举值的钉子。
/// </summary>
/// <remarks>
/// <para>
/// 这里的每个期望值都取自上游 <c>WebView2.dll</c> 的元数据（<c>FieldDef</c> 的 Constant blob），
/// 不是照文档抄的。之所以要单独钉住：这些值错了不会报任何错，只会让某个交互静默失效。
/// </para>
/// <para>
/// 有过一次实例：<c>WHEEL</c> 写成 <c>0x020E</c>（那是 HORIZONTAL_WHEEL 的值），
/// <c>LEAVE</c> 写成 <c>0x020A</c>（那是 WHEEL 的值），
/// <c>VIRTUAL_KEYS</c> 整组错位——症状是"滚轮完全不滚"、"鼠标移出后 hover 残留"，
/// 而所有 selftest 全绿（它们不测鼠标注入）。
/// </para>
/// </remarks>
public sealed class WebView2EnumTests
{
    [Fact]
    public void MouseEventKind_MatchesUpstreamValues()
    {
        Assert.Equal(0x0200, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_MOVE);
        Assert.Equal(0x0201, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_LEFT_BUTTON_DOWN);
        Assert.Equal(0x0202, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_LEFT_BUTTON_UP);
        Assert.Equal(0x0203, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_LEFT_BUTTON_DOUBLE_CLICK);
        Assert.Equal(0x0204, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_RIGHT_BUTTON_DOWN);
        Assert.Equal(0x0205, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_RIGHT_BUTTON_UP);
        Assert.Equal(0x0206, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_RIGHT_BUTTON_DOUBLE_CLICK);
        Assert.Equal(0x0207, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_MIDDLE_BUTTON_DOWN);
        Assert.Equal(0x0208, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_MIDDLE_BUTTON_UP);
        Assert.Equal(0x0209, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_MIDDLE_BUTTON_DOUBLE_CLICK);
        Assert.Equal(0x020A, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_WHEEL);
        Assert.Equal(0x020B, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_X_BUTTON_DOWN);
        Assert.Equal(0x020C, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_X_BUTTON_UP);
        Assert.Equal(0x020D, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_X_BUTTON_DOUBLE_CLICK);
        Assert.Equal(0x020E, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_HORIZONTAL_WHEEL);
        Assert.Equal(0x02A3, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_LEAVE);
        Assert.Equal(0x00A4, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_NON_CLIENT_RIGHT_BUTTON_DOWN);
        Assert.Equal(0x00A5, (int)COREWEBVIEW2_MOUSE_EVENT_KIND.COREWEBVIEW2_MOUSE_EVENT_KIND_NON_CLIENT_RIGHT_BUTTON_UP);
    }

    [Fact]
    public void MouseEventVirtualKeys_MatchesUpstreamValues()
    {
        Assert.Equal(0x0000, (int)COREWEBVIEW2_MOUSE_EVENT_VIRTUAL_KEYS.COREWEBVIEW2_MOUSE_EVENT_VIRTUAL_KEYS_NONE);
        Assert.Equal(0x0001, (int)COREWEBVIEW2_MOUSE_EVENT_VIRTUAL_KEYS.COREWEBVIEW2_MOUSE_EVENT_VIRTUAL_KEYS_LEFT_BUTTON);
        Assert.Equal(0x0002, (int)COREWEBVIEW2_MOUSE_EVENT_VIRTUAL_KEYS.COREWEBVIEW2_MOUSE_EVENT_VIRTUAL_KEYS_RIGHT_BUTTON);
        Assert.Equal(0x0004, (int)COREWEBVIEW2_MOUSE_EVENT_VIRTUAL_KEYS.COREWEBVIEW2_MOUSE_EVENT_VIRTUAL_KEYS_SHIFT);
        Assert.Equal(0x0008, (int)COREWEBVIEW2_MOUSE_EVENT_VIRTUAL_KEYS.COREWEBVIEW2_MOUSE_EVENT_VIRTUAL_KEYS_CONTROL);
        Assert.Equal(0x0010, (int)COREWEBVIEW2_MOUSE_EVENT_VIRTUAL_KEYS.COREWEBVIEW2_MOUSE_EVENT_VIRTUAL_KEYS_MIDDLE_BUTTON);
        Assert.Equal(0x0020, (int)COREWEBVIEW2_MOUSE_EVENT_VIRTUAL_KEYS.COREWEBVIEW2_MOUSE_EVENT_VIRTUAL_KEYS_X_BUTTON1);
        Assert.Equal(0x0040, (int)COREWEBVIEW2_MOUSE_EVENT_VIRTUAL_KEYS.COREWEBVIEW2_MOUSE_EVENT_VIRTUAL_KEYS_X_BUTTON2);
    }

    [Fact]
    public void MoveFocusReason_MatchesUpstreamValues()
    {
        Assert.Equal(0, (int)COREWEBVIEW2_MOVE_FOCUS_REASON.COREWEBVIEW2_MOVE_FOCUS_REASON_PROGRAMMATIC);
        Assert.Equal(1, (int)COREWEBVIEW2_MOVE_FOCUS_REASON.COREWEBVIEW2_MOVE_FOCUS_REASON_NEXT);
        Assert.Equal(2, (int)COREWEBVIEW2_MOVE_FOCUS_REASON.COREWEBVIEW2_MOVE_FOCUS_REASON_PREVIOUS);
    }
}
